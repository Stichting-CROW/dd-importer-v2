-- Description: Manual rejections of data on the Datakwaliteit page
-- (dashboarddeelmobiliteit-app#266). An admin marks a period in which the data
-- of one operator, or all operators, should not be used. The dashboard API
-- reads and writes this table; deleting a rejection sets deleted_by/deleted_at.
--
-- Run after 20261125_add_data_type_to_feeds.sql, which creates feed_data_type.

BEGIN;

CREATE TABLE IF NOT EXISTS data_quality_rejection (
    rejection_id   INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    start_time     TIMESTAMPTZ NOT NULL,
    end_time       TIMESTAMPTZ,                       -- NULL = ongoing
    system_id      VARCHAR(255),                      -- NULL = all operators
    municipalities VARCHAR(255)[],                    -- gm_codes; NULL = all of NL
    modalities     VARCHAR(255)[],                    -- form factors; NULL = all
    data_types     feed_data_type[] NOT NULL,
    issue_owner    VARCHAR(30) NOT NULL
                   CHECK (issue_owner IN ('operator', 'dashboard_deelmobiliteit')),
    note           TEXT NOT NULL DEFAULT '',
    created_by     VARCHAR(255) NOT NULL,
    created_at     TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_by     VARCHAR(255),
    updated_at     TIMESTAMPTZ,
    deleted_by     VARCHAR(255),
    deleted_at     TIMESTAMPTZ,
    CHECK (end_time IS NULL OR end_time > start_time),
    CHECK (cardinality(data_types) > 0),
    CHECK (municipalities IS NULL OR cardinality(municipalities) > 0),
    CHECK (modalities IS NULL OR cardinality(modalities) > 0)
);

CREATE INDEX IF NOT EXISTS idx_data_quality_rejection_system_id
    ON data_quality_rejection (system_id)
    WHERE deleted_at IS NULL;

COMMENT ON TABLE data_quality_rejection IS
    'Manual rejections of operator data, shown on the Datakwaliteit page. NULL in system_id, municipalities or modalities means all.';

GRANT SELECT, INSERT, UPDATE ON TABLE data_quality_rejection TO dashboarddeelmobiliteit;

COMMIT;
